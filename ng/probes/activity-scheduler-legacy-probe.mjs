import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ContentDocumentStore } from "../core/ContentDocumentStore.js";
import { ActivityDefinitionStore } from "../core/ActivityDefinitionStore.js";
import { ActivityQueueRegistry } from "../core/ActivityQueueRegistry.js";
import { ActivityScheduler } from "../core/ActivityScheduler.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../data");
const loader = { loadJSON: async (file) => JSON.parse(await fs.readFile(path.join(root, file), "utf8")) };
const contents = new ContentDocumentStore(loader);
await contents.loadManifest("legacy-content-manifest.json");
const definitions = new ActivityDefinitionStore(loader);
const queues = new ActivityQueueRegistry();
queues.register("work");
queues.register("social");
const scheduler = new ActivityScheduler({ contentDocumentStore: contents, activityDefinitionStore: definitions, queueRegistry: queues, context: {} });
const catalog = scheduler.load();
assert.equal(contents.list().length, 54);
assert.ok(scheduler.slots.size > 0);
assert.ok(catalog.size > 0);
assert.ok(definitions.list().length > 0);
assert.ok(Array.isArray(scheduler.diagnostics));
console.log(`activity-scheduler legacy probe: documents=${contents.list().length} catalog=${catalog.size} definitions=${definitions.list().length} diagnostics=${scheduler.diagnostics.length}`);
